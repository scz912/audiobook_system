import '_json_helpers.dart';

/* The Al-Quran pack. The app ships a small manifest (assets/quran/
   quran_manifest.json) that lists every chapter and how big it is; the
   audio and GIFs themselves are downloadable content hosted as GitHub
   release assets at [baseUrl]. The manifest is generated by
   tools/quran_pack/package_pack.py. */
class QuranManifest {
  final String packId;
  final String baseUrl;
  final String reciter;
  final int bitrateKbps;
  final List<QuranElement> elements;
  final List<QuranChapter> chapters;
  final List<QuranSource> sources;

  const QuranManifest({
    required this.packId,
    required this.baseUrl,
    required this.reciter,
    required this.bitrateKbps,
    required this.elements,
    required this.chapters,
    required this.sources,
  });

  int get totalVerses => chapters.fold(0, (sum, c) => sum + c.verseCount);

  // Everything a full download pulls: every chapter zip plus every GIF.
  int get totalDownloadBytes =>
      chapters.fold(0, (sum, c) => sum + c.downloadBytes) +
      elements.fold(0, (sum, e) => sum + e.bytes);

  QuranElement? elementById(String id) {
    for (final e in elements) {
      if (e.id == id) return e;
    }
    return null;
  }

  factory QuranManifest.fromJson(Map<String, dynamic> json) {
    List<T> listOf<T>(String key, T Function(Map<String, dynamic>) parse) {
      final raw = json[key];
      return raw is List
          ? raw.whereType<Map<String, dynamic>>().map(parse).toList()
          : <T>[];
    }

    return QuranManifest(
      packId: safeString(json['pack_id']),
      baseUrl: safeString(json['base_url']),
      reciter: safeString(json['reciter']),
      bitrateKbps: safeInt(json['bitrate_kbps']) ?? 64,
      elements: listOf('elements', QuranElement.fromJson),
      chapters: listOf('chapters', QuranChapter.fromJson),
      sources: listOf('sources', QuranSource.fromJson),
    );
  }
}

/* A nature element (fire, ocean, forest...) whose looping GIF plays behind
   a chapter's verses. */
class QuranElement {
  final String id;
  final String nameEn;
  final String nameMs;
  final String file;
  final int bytes;
  final String credit;
  final String license;
  final String sourceUrl;

  const QuranElement({
    required this.id,
    required this.nameEn,
    required this.nameMs,
    required this.file,
    required this.bytes,
    required this.credit,
    required this.license,
    required this.sourceUrl,
  });

  String name(String languageCode) => languageCode == 'ms' ? nameMs : nameEn;

  factory QuranElement.fromJson(Map<String, dynamic> json) => QuranElement(
        id: safeString(json['id']),
        nameEn: safeString(json['name_en']),
        nameMs: safeString(json['name_ms']),
        file: safeString(json['file']),
        bytes: safeInt(json['bytes']) ?? 0,
        credit: safeString(json['credit']),
        license: safeString(json['license']),
        sourceUrl: safeString(json['source_url']),
      );
}

class QuranChapter {
  final int number;
  final String nameAr;
  final String nameEn; // transliterated, e.g. "Al-Faatiha"
  final String meaningEn; // e.g. "The Opening"
  final String revelation; // Meccan | Medinan
  final int verseCount;
  final String elementId;
  // true when the element comes from the chapter's theme (e.g. Ar-Ra'd ->
  // thunder); false when it was picked at random.
  final bool elementFromTheme;
  final String file;
  final int downloadBytes;
  final int installedBytes;

  const QuranChapter({
    required this.number,
    required this.nameAr,
    required this.nameEn,
    required this.meaningEn,
    required this.revelation,
    required this.verseCount,
    required this.elementId,
    required this.elementFromTheme,
    required this.file,
    required this.downloadBytes,
    required this.installedBytes,
  });

  factory QuranChapter.fromJson(Map<String, dynamic> json) => QuranChapter(
        number: safeInt(json['number']) ?? 0,
        nameAr: safeString(json['name_ar']),
        nameEn: safeString(json['name_en']),
        meaningEn: safeString(json['meaning_en']),
        revelation: safeString(json['revelation']),
        verseCount: safeInt(json['verses']) ?? 0,
        elementId: safeString(json['element']),
        elementFromTheme: safeString(json['element_reason']) == 'theme',
        file: safeString(json['file']),
        downloadBytes: safeInt(json['bytes']) ?? 0,
        installedBytes: safeInt(json['installed_bytes']) ?? 0,
      );
}

class QuranSource {
  final String title;
  final String detail;
  final String url;
  final String license;

  const QuranSource({
    required this.title,
    required this.detail,
    required this.url,
    required this.license,
  });

  factory QuranSource.fromJson(Map<String, dynamic> json) => QuranSource(
        title: safeString(json['title']),
        detail: safeString(json['detail']),
        url: safeString(json['url']),
        license: safeString(json['license']),
      );
}

/* One verse of a downloaded chapter, read from the chapter's verses.json.
   Arabic only: the pack carries no translations, since their publishers
   haven't licensed redistributing the full text. */
class QuranVerse {
  final int number;
  final String arabic;
  final String audioFile; // file name inside the chapter folder

  const QuranVerse({
    required this.number,
    required this.arabic,
    required this.audioFile,
  });

  factory QuranVerse.fromJson(Map<String, dynamic> json) => QuranVerse(
        number: safeInt(json['n']) ?? 0,
        arabic: safeString(json['ar']),
        audioFile: safeString(json['audio']),
      );
}

/* A downloaded chapter: its verses plus the optional Bismillah clip that
   plays before verse 1 (every chapter except 1 and 9). */
class QuranChapterContent {
  final List<QuranVerse> verses;
  final String? bismillahAudio;

  const QuranChapterContent({required this.verses, this.bismillahAudio});

  factory QuranChapterContent.fromJson(Map<String, dynamic> json) {
    final raw = json['verses'];
    return QuranChapterContent(
      verses: raw is List
          ? raw
              .whereType<Map<String, dynamic>>()
              .map(QuranVerse.fromJson)
              .toList()
          : const [],
      bismillahAudio: safeNullableString(json['bismillah_audio']),
    );
  }
}
